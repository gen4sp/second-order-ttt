"""Write the E1-VE configs: wave 1, wave 2, the GPU profile gate and the GPU smoke.

Run from the repository root: ``uv run --locked python scripts/e1ve_configs.py``.
Cells are listed longest first (SO, AICE, then the plain first-order rules) so the
worker pool drains evenly. The lesion arm (FO-CE with the C copy edges blocked,
``edge = true``) is a plain FO-CE run and goes last.
"""
from pathlib import Path

SEEDS = range(10, 16)          # registered seeds; 0, 100, 101 were design pilots
ETAS = (10.0, 40.0)
WAVE1_ARMS = (("so", "ce", False), ("fo", "aice", False), ("fo", "linev", False),
              ("fo", "ce", False), ("fo", "ce", True))
WAVE2_SLIPS = (0.10, 0.05, 0.03, 0.01)

HEADER = """experiment = "ve"
seed = 0

[ve]
process_name = "{name}"
device = "{device}"
workers = {workers}
max_minutes = {minutes}
# fp32 IEEE matmuls: the step is not matmul-bound at d=128
tf32 = false
fused_adam = true
compile_backbone = {compile}
steps = {steps}
quick_every = {quick}
n_eval = {n_eval}
save_final = {save}
"""


def cell(order, rule, edge, eta, slip, seed):
    lesion = ", edge = true" if edge else ""
    return (f'  {{ order = "{order}", rule = "{rule}"{lesion}, eta = {eta:g}, slip = {slip:g}, '
            f'seed = {seed} }},')


def write(path, cells, comment, **kw):
    kw = dict(dict(device="cuda", workers=6, minutes=150, compile="false", steps=2000, quick=25,
                   n_eval=256, save="true"), **kw)
    text = f"# {comment}\n# Generated by scripts/e1ve_configs.py.\n" + HEADER.format(**kw)
    text += "cells = [\n" + "\n".join(cells) + "\n]\n"
    Path(path).parent.mkdir(parents=True, exist_ok=True)
    Path(path).write_text(text)
    print(f"{path}: {len(cells)} cells")


def main():
    wave1 = [cell(o, r, e, eta, 0.0, s) for o, r, e in WAVE1_ARMS for eta in ETAS for s in SEEDS]
    write("configs/e1-ve/ve.toml", wave1,
          "E1-VE wave 1: SO-CE / FO-AICE / FO-linev / FO-CE / FO-CE copy-edge lesion "
          "x eta 10, 40 x seeds 10-15, no slip.",
          name="TTM-ve-10")
    wave2 = [cell("fo", "ce", False, eta, slip, s)
             for slip in WAVE2_SLIPS for eta in ETAS for s in SEEDS]
    write("configs/e1-ve/wave2.toml", wave2,
          "E1-VE wave 2: FO-CE x slip .01/.03/.05/.10 x eta 10, 40 x seeds 10-15. "
          "Run only if wave 1 shows the FO-CE A/N failure.",
          name="TTM-ve-20")
    # 2 x workers cells, longest first. The first `workers` are all SO, as at the start of
    # wave 1 (12 SO cells first), so the whole-device memory is measured under an all-SO
    # pool; the rest follow the wave's arm mix. RUN_SUMMARY's rate is end-to-end.
    def profile(workers):
        so = [("so", "ce", False, 90 + i) for i in range(workers)]
        mix = [(o, r, e, 90 + workers + i) for i in range(workers) for o, r, e in WAVE1_ARMS[1:]]
        mix = sorted(mix[:workers], key=lambda c: WAVE1_ARMS.index(c[:3]))
        return [cell(o, r, e, 10.0, 0.0, s) for o, r, e, s in so + mix]

    for run, workers in ((5, 6), (6, 8), (7, 10)):
        for compiled in (False, True):
            suffix = "-compile" if compiled else ""
            write(f"configs/e1-ve/profile-w{workers}{suffix}.toml", profile(workers),
                  f"E1-VE GPU profile gate, {workers} workers"
                  f"{', regional torch.compile of the backbone blocks' if compiled else ''}: "
                  "throughput and memory only, never scored.",
                  # only the compile profile at the chosen worker count is run; it takes process number 08
                  name=f"TTM-ve-08-profc-w{workers}" if compiled else f"TTM-ve-0{run}-prof",
                  workers=workers,
                  minutes=15, steps=150, quick=50, n_eval=32, save="false",
                  compile="true" if compiled else "false")
    write("configs/e1-ve/gpu-smoke.toml", [cell(o, r, e, 40.0, 0.03, 99) for o, r, e in WAVE1_ARMS],
          "E1-VE GPU smoke: one short cell per arm at the harder eta with slip.",
          name="TTM-ve-09-smoke", workers=5, minutes=10, steps=50, quick=25, n_eval=32,
          save="false")


if __name__ == "__main__":
    main()
